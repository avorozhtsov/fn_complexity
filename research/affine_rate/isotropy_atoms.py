def n_k_small(space: JetSpace, atoms_codes: np.ndarray, targets: np.ndarray,
              limit: int) -> int | None:
    """``N_k`` by plain exhaustive subset search.  Only for small atom sets."""

    atoms = space.decode(atoms_codes).astype(np.int64)
    atoms = atoms[atoms.any(axis=1)]
    return cover_cost(space.q, atoms, targets.astype(np.int64), limit)


def n_k_le_hull_plus_one(space: JetSpace, atoms_codes: np.ndarray,
                         targets: np.ndarray) -> int | None:
    """Decide ``N_k <= k + 1`` exhaustively, where ``k = targets.shape[0]``.

    If a solution with ``r`` atoms exists then ``U = span(atoms chosen)`` has
    ``dim U <= r`` and contains the hull ``H = span(targets)``, of dimension
    ``k``.  For ``r = k + 1`` therefore ``U = H`` or ``U = H + <a>`` for one
    atom ``a``, and every chosen atom lies in ``U``.  So it suffices to look, for
    each atom ``a``, at the atoms inside the ``(k+1)``-dimensional space
    ``H + <a>`` -- an exhaustive case distinction.
    """

    q = space.q
    k = targets.shape[0]
    hull = Subspace(q, space.dim).extended_many(targets.astype(np.int64))
    assert hull.dimension == k
    atom_set = atoms_codes

    def atoms_inside(sub: Subspace) -> np.ndarray:
        elements = sub.elements()
        codes = space.encode(elements)
        position = np.searchsorted(atom_set, codes)
        position = np.clip(position, 0, atom_set.shape[0] - 1)
        keep = atom_set[position] == codes
        rows = elements[keep]
        return rows[rows.any(axis=1)]

    best = cover_cost(q, atoms_inside(hull), targets.astype(np.int64), k + 1)
    if best == k:
        return best        # k is the absolute minimum, no need to look further

    # the distinct spaces H + <a> are indexed by atoms modulo H, normalised by
    # scaling the leading nonzero entry of the residual to 1
    direction_codes: list[np.ndarray] = []
    step = 1 << 17
    for start in range(0, atom_set.shape[0], step):
        residuals = hull.reduce(space.decode(atom_set[start:start + step]).astype(np.int64))
        residuals = residuals[residuals.any(axis=1)]
        if not residuals.shape[0]:
            continue
        pivot = (residuals != 0).argmax(axis=1)
        leading = residuals[np.arange(residuals.shape[0]), pivot]
        inverse = np.array([pow(int(v), q - 2, q) for v in range(q)], dtype=np.int64)
        residuals = (residuals * inverse[leading][:, None]) % q
        direction_codes.append(np.unique(space.encode(residuals)))
    for row in space.decode(np.unique(np.concatenate(direction_codes))).astype(np.int64):
        bigger = hull.extended(row)
        cost = cover_cost(q, atoms_inside(bigger), targets.astype(np.int64), k + 1)
        if cost is not None and (best is None or cost < best):
            best = cost
            if best == k:
                break
    return best
